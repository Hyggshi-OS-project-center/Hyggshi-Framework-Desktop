// ts-emitter.ts — schema JSON (from core/bindings_schema.go) → TypeScript.
//
// Strategy: pre-walk the whole graph collecting every named type (named struct
// or named type), declare each once, then render TS expressions pointing at
// that name. Anonymous struct → inline object literal. Cross-package name
// collision → suffix.

// ---- schema types (wire format of core/bindings_schema.go) ------------------

export interface SchemaField {
	name: string;
	type: SchemaNode;
}

export type SchemaNode = {
	/** named type / struct name (absent on composites) */
	name?: string;
	pkg?: string;
	/** struct | array | ptr | map | string | number | bool | … */
	kind: string;
	/** struct only */
	fields?: SchemaField[];
	/** array / ptr only */
	elem?: SchemaNode;
	/** map only */
	key?: SchemaNode;
	/** map only */
	val?: SchemaNode;
};

export interface SchemaBinding {
	name: string;
	in: SchemaNode;
	out: SchemaNode;
}

export interface Schema {
	bindings?: SchemaBinding[];
	error?: string;
}

export interface EmittedBindings {
	dts: string;
	js: string;
}

export function emitBindings(schema: Schema): EmittedBindings {
	const named = new Map<string, SchemaNode>(); // key "pkg.Name" → node
	const tsNames = new Map<string, string>(); // key → final TS name

	for (const b of schema.bindings ?? []) {
		collectNamed(b.in, named);
		collectNamed(b.out, named);
	}

	// assign TS names, suffix _2, _3… on collision
	const usedNames = new Set<string>();
	for (const [key, node] of named) {
		let name = node.name ?? key;
		for (let i = 2; usedNames.has(name); i++) name = `${node.name}_${i}`;
		usedNames.add(name);
		tsNames.set(key, name);
	}

	const decls = [...named.keys()].map((key) =>
		declareType(named.get(key) as SchemaNode, tsNames.get(key) as string, tsNames),
	);

	const handlerEntries = (schema.bindings ?? []).map(
		(b) => `\t${b.name}: [${tsOf(b.in, tsNames)}, ${tsOf(b.out, tsNames)}];`,
	);

	const dts = [
		"// GENERATED by `hfd bindings` — DO NOT edit by hand.",
		"// Source of truth: the hfd.BindTyped functions in Go.",
		"",
		...decls,
		"",
		"export interface HFDHandlers {",
		...handlerEntries,
		"}",
		"",
		"export declare function call<K extends keyof HFDHandlers>(",
		"\tname: K,",
		"\targs: HFDHandlers[K][0],",
		"): Promise<HFDHandlers[K][1]>;",
		"export declare function on(name: string, cb: (data: unknown) => void): () => void;",
		"export declare function off(name: string, cb: (data: unknown) => void): void;",
		"",
	].join("\n");

	const js = [
		"// GENERATED by `hfd bindings` — glue around window.hfd (injected by the Go runtime).",
		'if (typeof window !== "undefined") {',
		"\twindow.hfdAPI = {",
		"\t\tcall(name, args) { return window.hfd.call(name, args); },",
		"\t\ton(name, cb) { return window.hfd.on(name, cb); },",
		"\t\toff(name, cb) { window.hfd.off(name, cb); },",
		"\t};",
		"}",
		"export function call(name, args) {",
		"\treturn window.hfd.call(name, args);",
		"}",
		"export function on(name, cb) {",
		"\treturn window.hfd.on(name, cb);",
		"}",
		"export function off(name, cb) {",
		"\twindow.hfd.off(name, cb);",
		"}",
		"",
	].join("\n");

	return { dts, js };
}

// ---- collect: walk the graph, gather every named type -----------------------

function collectNamed(node: SchemaNode | undefined, out: Map<string, SchemaNode>): void {
	if (!node) return;
	if (node.name) {
		const key = `${node.pkg ?? "<root>"}.${node.name}`;
		if (node.kind === "struct") {
			if (!out.has(key)) {
				out.set(key, node);
				for (const f of node.fields ?? []) collectNamed(f.type, out);
				return;
			}
		} else {
			out.set(key, node);
		}
	}
	switch (node.kind) {
		case "array":
		case "ptr":
			collectNamed(node.elem, out);
			break;
		case "map":
			collectNamed(node.key, out);
			collectNamed(node.val, out);
			break;
		case "struct": // anonymous struct
			for (const f of node.fields ?? []) collectNamed(f.type, out);
			break;
	}
}

// ---- declare: emit "export interface X" or "export type X" ------------------

function declareType(
	node: SchemaNode,
	tsName: string,
	names: Map<string, string>,
): string {
	if (node.kind === "struct") {
		const fields = (node.fields ?? [])
			.map((f) => `\t${f.name}: ${tsOf(f.type, names)};`)
			.join("\n");
		return `export interface ${tsName} {\n${fields || "\t// empty struct"}\n}`;
	}
	// named type over primitive/slice/map → alias of the underlying
	return `export type ${tsName} = ${tsOf({ ...node, name: "", pkg: "" }, names)};`;
}

// ---- render TS expressions ---------------------------------------------------

const PRIMITIVES: Record<string, string> = {
	string: "string",
	number: "number",
	bool: "boolean",
};

function tsOf(node: SchemaNode | undefined, names: Map<string, string>): string {
	if (!node) return "unknown";
	if (node.name) {
		const key = `${node.pkg ?? "<root>"}.${node.name}`;
		return names.get(key) ?? node.name;
	}
	switch (node.kind) {
		case "array":
			return `${tsOf(node.elem, names)}[]`;
		case "ptr":
			return `${tsOf(node.elem, names)} | null`;
		case "map":
			return `Record<${node.key && node.key.kind === "string" ? "string" : tsOf(node.key, names)}, ${tsOf(node.val, names)}>`;
		case "struct": // anonymous
			return `{ ${(node.fields ?? [])
				.map((f) => `${f.name}: ${tsOf(f.type, names)}`)
				.join("; ")} }`;
		default:
			return PRIMITIVES[node.kind] ?? "unknown";
	}
}
